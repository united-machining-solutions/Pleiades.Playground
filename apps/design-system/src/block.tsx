import type { ReactNode } from "react"

import { cn } from "@pleiades/ui/lib/utils"

// The frame of the design system page: a section, a block for one component, and the box an
// example stands in. They are the layout of this page and nothing a screen of the app would use.

/** The sections of the page, in their order: the header jumps to them. */
export const sections = [
  { id: "foundations", title: "Foundations" },
  { id: "actions", title: "Actions" },
  { id: "inputs", title: "Inputs" },
  { id: "navigation", title: "Navigation" },
  { id: "data-display", title: "Data display" },
  { id: "feedback", title: "Feedback" },
  { id: "overlays", title: "Overlays" },
  { id: "conversation", title: "Conversation" },
  { id: "do-and-dont", title: "Do and Don't" },
  { id: "built-from-these", title: "Built from these" },
] as const

type SectionId = (typeof sections)[number]["id"]

/** A token or a class in a sentence, set so that its hyphens never part at the end of a line. */
export function Token({ children }: { children: string }) {
  return <code className="font-mono text-[0.85em] whitespace-nowrap">{children}</code>
}

/** One section. The row of jumps is sticky, so a jump stops below it. */
export function Section({ id, line, children }: { id: SectionId; line: ReactNode; children: ReactNode }) {
  const title = sections.find((section) => section.id === id)?.title
  return (
    <section id={id} aria-labelledby={`${id}-title`} className="flex scroll-mt-20 flex-col gap-10">
      <div className="flex flex-col gap-1 border-b pb-4">
        <h2 id={`${id}-title`} className="text-lg font-semibold">
          {title}
        </h2>
        <p className="max-w-prose text-sm text-muted-foreground">{line}</p>
      </div>
      {children}
    </section>
  )
}

const docsOf = {
  shadcn: (file: string) => `https://ui.shadcn.com/docs/components/base/${file}`,
  "base-ui": (file: string) => `https://base-ui.com/react/components/${file}`,
}

/**
 * One component: its name, when to take it, where to import it from and where its docs are.
 * `file` is the file name under packages/ui/src/components. A component that is ours and not
 * generated by shadcn says so, and its docs are those of Base UI.
 */
export function Block({
  name,
  file,
  line,
  ours = false,
  children,
}: {
  name: string
  file: string
  line: ReactNode
  ours?: boolean
  children: ReactNode
}) {
  return (
    <article id={file} className="flex scroll-mt-20 flex-col gap-4">
      <div className="flex flex-col gap-1">
        <div className="flex flex-wrap items-baseline justify-between gap-x-4 gap-y-1">
          <h3 className="text-base font-medium">{name}</h3>
          <p className="text-xs text-muted-foreground">
            <code className="font-mono">@pleiades/ui/components/{file}</code>
            {" · "}
            <a
              href={docsOf[ours ? "base-ui" : "shadcn"](file)}
              target="_blank"
              rel="noreferrer"
              className="underline underline-offset-4 hover:text-foreground"
            >
              Docs<span className="sr-only"> of {name} (opens in a new tab)</span>
            </a>
          </p>
        </div>
        <p className="max-w-prose text-sm text-muted-foreground">{line}</p>
        {ours && <p className="text-sm text-muted-foreground">Ours, on Base UI: shadcn has no file for it.</p>}
      </div>
      {children}
    </article>
  )
}

/** One topic of a section that is no component: a foundation, a rule, a thing built from components. */
export function Topic({ title, line, children }: { title: string; line: ReactNode; children: ReactNode }) {
  return (
    <article className="flex flex-col gap-4">
      <div className="flex flex-col gap-1">
        <h3 className="text-base font-medium">{title}</h3>
        <p className="max-w-prose text-sm text-muted-foreground">{line}</p>
      </div>
      {children}
    </article>
  )
}

/**
 * The box an example stands in, with what it shows as its caption. An example of what not to do
 * says so in the colour of an error, on its caption only.
 */
export function Example({
  title,
  dont = false,
  className,
  children,
}: {
  title?: ReactNode
  dont?: boolean
  className?: string
  children: ReactNode
}) {
  return (
    <figure className="flex min-w-0 flex-col gap-2">
      {title && (
        <figcaption className={cn("text-sm", dont ? "font-medium text-destructive" : "text-muted-foreground")}>
          {title}
        </figcaption>
      )}
      <div className={cn("flex min-w-0 flex-wrap items-center gap-3 rounded-lg border p-6", className)}>
        {children}
      </div>
    </figure>
  )
}

/** Examples side by side where there is room for two. */
export function Examples({ className, children }: { className?: string; children: ReactNode }) {
  return <div className={cn("grid gap-4 md:grid-cols-2", className)}>{children}</div>
}
